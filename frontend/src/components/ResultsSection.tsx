    if (reportControllerRef.current) {
      reportControllerRef.current.abort();
      reportControllerRef.current = null;
    }

    axios.post(`${API_BASE_URL}/cleanup_files`).catch(err => {
      console.error('Cleanup failed:', err);
    });

    onNewAnalysis();
